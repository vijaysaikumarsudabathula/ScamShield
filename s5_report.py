def architecture():
    fig, ax = plt.subplots(figsize=(14, 7.2)); ax.set_xlim(0, 14); ax.set_ylim(0, 7.2); ax.axis("off")
    def box(x, y, w, h, t, fc, fs=10, bold=False):
        ax.add_patch(FancyBboxPatch((x, y), w, h, boxstyle="round,pad=0.04,rounding_size=0.12", fc=fc, ec="k", lw=1.2))
        ax.text(x + w / 2, y + h / 2, t, ha="center", va="center", fontsize=fs, fontweight="bold" if bold else "normal")
    def arr(x1, y1, x2, y2, **kw):
        ax.add_patch(FancyArrowPatch((x1, y1), (x2, y2), arrowstyle="-|>", mutation_scale=16, lw=1.6, color="#333", **kw))
    box(0.2, 2.65, 1.9, 1.4, "Incoming\nmessage\n(SMS / chat / email)", "#FFF3CD", 10, True)
    box(2.8, 4.7, 2.5, 1.4, "② ANALYZER agent\nmanipulation tactics\n(urgency, fear, reward…)", "#D6EAF8")
    box(2.8, 2.65, 2.5, 1.4, "① EXTRACTOR agent\nURLs · phones · amounts", "#D6EAF8")
    box(2.8, 0.6, 2.5, 1.4, "③ VERIFIER agent\ndomain intelligence\n(DB lookup, look-alikes)", "#D6EAF8")
    box(6.1, 4.7, 2.6, 1.4, "ADVERSARIAL LOOP (offline)\nattacker rewrites scams →\ndefender retrains", "#FDEBD0", 9)
    box(6.1, 2.65, 2.6, 1.4, "TEXT MODEL\ncanonicaliser + TF-IDF\n+ best ML ensemble\n(adversarially hardened)", "#D5F5E3", 9)
    box(6.1, 0.6, 2.6, 1.4, "DOMAIN MODEL\n67 lexical / brand features\n+ phishing-DB lookup", "#D5F5E3", 9)
    box(9.4, 2.65, 2.0, 1.4, "④ SCORER\nnoisy-OR fusion\nrisk 0 → 1", "#FADBD8", 10, True)
    box(12.0, 2.65, 1.8, 1.4, "⑤ ADVISOR\nverdict · evidence\nnext steps", "#E8DAEF", 10, True)
    arr(2.1, 3.7, 2.8, 5.2); arr(2.1, 3.35, 2.8, 3.35)                      # message -> analyzer / extractor
    arr(5.3, 3.35, 6.1, 3.35)                                               # extractor -> text model
    arr(4.05, 2.65, 4.05, 2.0)                                              # extractor -> verifier
    arr(5.3, 1.3, 6.1, 1.3)                                                 # verifier -> domain model
    arr(8.7, 3.35, 9.4, 3.35)                                               # text model -> scorer
    arr(8.7, 1.5, 9.5, 2.65)                                                # domain model -> scorer
    arr(11.4, 3.35, 12.0, 3.35)                                             # scorer -> advisor
    ax.annotate("", xy=(7.4, 4.1), xytext=(7.4, 4.7), arrowprops=dict(arrowstyle="<->", lw=1.6, color="#B9770E"))
    ax.plot([4.05, 4.05, 12.9], [6.1, 6.7, 6.7], color="#333", lw=1.6); arr(12.9, 6.7, 12.9, 4.1)   # analyzer -> advisor (tactics)
    ax.text(8.5, 6.82, "tactics & evidence", fontsize=8, ha="center", color="#333")
    ax.set_title("ScamShield architecture - multi-agent, explainable scam checking with an attacker-vs-defender training loop", fontweight="bold")
    savefig("00_architecture.png")


def dashboard():
    T = lambda n: pd.read_csv(TAB / f"{n}.csv")
    sms, url = T("sms_test_metrics"), T("url_test_metrics"); adv = T("adv_final_summary"); pm = T("probe_model_comparison")
    fig, ax = plt.subplots(2, 2, figsize=(15, 10.5))
    bests = {"sms": T("sms_cv_metrics_mean").sort_values(["F1", "PR-AUC"], ascending=False).Model.iloc[0],
             "url": T("url_cv_metrics_mean").sort_values(["F1", "PR-AUC"], ascending=False).Model.iloc[0]}
    for a, d, ttl, bk in [(ax[0, 0], sms, "SMS scam detection - test F1 (red = best by 5-fold CV F1)", "sms"),
                          (ax[0, 1], url, "Phishing-domain detection - test F1 (red = best by CV F1)", "url")]:
        d = d.sort_values("F1"); a.barh(d.Model, d.F1, color=[C_SPAM if m == bests[bk] else C_HAM for m in d.Model], edgecolor="k")
        for i, v in enumerate(d.F1): a.text(v + .002, i, f"{v:.3f}", va="center", fontsize=8)
        a.set_xlim(max(0, d.F1.min() - .06), min(1.03, d.F1.max() + .04)); a.set_title(ttl)
    bm = adv.Model.iloc[0]; d = adv[adv.Model == bm].set_index("Config").loc[["Baseline", "+ Canonicalization", "+ Adversarial training", "+ Canon. & Adv. training"]]
    cols = ["Evasion (seen attacks)", "Evasion (unseen attacks)", "Evasion (all attacks)"]
    d[cols].plot.bar(ax=ax[1, 0], color=[C_HAM, C_ACC, C_SPAM], edgecolor="k", width=.8); ax[1, 0].set_ylim(0, 1)
    ax[1, 0].yaxis.set_major_formatter(plt.FuncFormatter(lambda v, _: f"{v:.0%}")); ax[1, 0].set_title(f"Evasion rate of obfuscated scams ({bm}) - lower is better")
    ax[1, 0].set_xticklabels(ax[1, 0].get_xticklabels(), rotation=12); ax[1, 0].set_xlabel(""); ax[1, 0].legend(fontsize=8)
    pm = pm.sort_values("Modern-probe F1"); ax[1, 1].barh(pm.Model, pm["Modern-probe F1"], color=C_ACC, edgecolor="k", label="modern probe F1")
    ax[1, 1].scatter(pm["SMS test F1"], range(len(pm)), color="k", marker="|", s=250, label="legacy SMS test F1", zorder=5)
    ax[1, 1].set_xlim(0, 1.02); ax[1, 1].set_title("Concept drift: legacy test F1 (|) vs modern-probe F1 (bar)"); ax[1, 1].legend(fontsize=8, loc="lower right")
    fig.suptitle("ScamShield - executive results dashboard", fontsize=16, fontweight="bold", y=1.0)
    savefig("01_executive_dashboard.png")


def workbook():
    path = ROOT / "ScamShield_Results.xlsx"
    with pd.ExcelWriter(path, engine="openpyxl") as xw:
        idx = pd.DataFrame([(s, d, c + ".csv") for c, s, d in SHEETS if (TAB / f"{c}.csv").exists()], columns=["Sheet", "Contents", "Source CSV"])
        pd.DataFrame({"README": NOTES}).to_excel(xw, sheet_name="README", index=False)
        idx.to_excel(xw, sheet_name="Index", index=False)
        for c, s, d in SHEETS:
            f = TAB / f"{c}.csv"
            if f.exists():
                pd.read_csv(f).to_excel(xw, sheet_name=s, index=False)
    wb = load_workbook(path)
    hdr_fill = PatternFill("solid", fgColor="1F3A5F"); good = PatternFill("solid", fgColor="C6EFCE"); thin = Side(style="thin", color="D0D0D0")
    name2csv = {s: c for c, s, _ in SHEETS}
    for ws in wb.worksheets:
        for row in ws.iter_rows():
            for cell in row:
                cell.font = Font(name="Arial", size=10); cell.border = Border(top=thin, bottom=thin, left=thin, right=thin)
                if isinstance(cell.value, float): cell.number_format = "0.0000"
        for cell in ws[1]:
            cell.font = Font(name="Arial", size=10, bold=True, color="FFFFFF"); cell.fill = hdr_fill
            cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        ws.freeze_panes = "B2" if ws.title not in ("README",) else None
        for i, col in enumerate(ws.columns, 1):
            L = max((len(str(c.value)) if c.value is not None else 0) for c in col[:200])
            ws.column_dimensions[get_column_letter(i)].width = min(max(10, L + 2), 70 if ws.title in ("README", "Probe_Set", "Agent_Demo", "ADV_Rounds") else 42)
        ws.row_dimensions[1].height = 30
        if ws.title == "README":
            ws.column_dimensions["A"].width = 160
            for r in ws.iter_rows(min_row=2):
                r[0].alignment = Alignment(wrap_text=True, vertical="top")
        if name2csv.get(ws.title) in HILITE:
            heads = [c.value for c in ws[1]]
            for m in METRICS:
                if m in heads:
                    j = heads.index(m) + 1; vals = [(ws.cell(r, j).value, r) for r in range(2, ws.max_row + 1) if isinstance(ws.cell(r, j).value, (int, float))]
                    if vals:
                        top = max(v for v, _ in vals)
                        for v, r in vals:
                            if abs(v - top) < 1e-12:
                                ws.cell(r, j).fill = good; ws.cell(r, j).font = Font(name="Arial", size=10, bold=True)
        if ws.title in ("Probe_Set", "Agent_Demo", "ADV_Rounds"):
            for r in ws.iter_rows(min_row=2):
                for c in r:
                    if isinstance(c.value, str) and len(c.value) > 60: c.alignment = Alignment(wrap_text=True, vertical="top")
    wb["README"].sheet_properties.tabColor = "1F3A5F"; wb.save(path)
    log(f"  workbook -> {path.name}  ({len(wb.sheetnames)} sheets)")


def run():
    log("STAGE 5 - report assets")
    architecture(); dashboard(); workbook(); log("STAGE 5 done")


if __name__ == "__main__":
    run()
